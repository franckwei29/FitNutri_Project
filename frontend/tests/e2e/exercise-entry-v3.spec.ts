import { test, expect } from '@playwright/test';
import { newOwner, history } from './v3-journeys';
import { beginExercise, activity, exerciseReview, confirmExercise, exerciseRoots } from './v3-exercise-journeys';
import { inspectOwnedSyntheticData } from './owned-db-verification.mjs';
test('TUX Quick: Basketball records outside Gym with no dated weight and keeps unavailable energy distinct from zero', async ({ page }) => {
    const owner = await newOwner(page, 'v3-ball');
    await beginExercise(page, '2019-12-31');
    await activity(page, 'Find activity or movement', 'basketball', 'Basketball');
    await page.getByLabel('Duration (minutes)', { exact: true }).fill('12.5');
    await exerciseReview(page);
    expect(inspectOwnedSyntheticData(owner.email).exerciseRecords).toHaveLength(0);
    const proof = await confirmExercise(page);
    expect(proof.roots.map(r => r.kind)).toEqual(['QUICK']);
    expect(proof.leaves).toHaveLength(1);
    await expect(page).toHaveURL(/\/dashboard$/);
    const roots = await exerciseRoots(page, '2019-12-31');
    expect(roots.results[0]).toMatchObject({ periodCount: 1, preview: { totalMinutes: 12.5, knownEnergyKj: null, partial: false, periods: [{ status: 'NO_WEIGHT', estimatedKj: null }] } });
    const data = inspectOwnedSyntheticData(owner.email);
    expect(data.exerciseRecords).toHaveLength(1);
    expect(data.exerciseRecords[0]).toMatchObject({ durationMinutes: 12.5, estimatedKj: null });
    await history(page, '2019-12-31', 'exercise');
    await expect(page.locator('article.saved-entry-root')).toHaveCount(1);
    await expect(page.locator('article.saved-entry-root')).toContainText('Energy estimate unavailable');
    await page.screenshot({ path: 'test-results/ux-v3/quick-no-weight.png', fullPage: true });
});
test('TUX Quick equipment: blank details save;invalid optional speed blocks;zero incline survives and details never alter MET energy', async ({ page }) => {
    const owner = await newOwner(page, 'v3-equipment');
    await beginExercise(page);
    await activity(page, 'Find activity or movement', 'Treadmill walking', 'Treadmill walking');
    await page.getByLabel('Duration (minutes)', { exact: true }).fill('20');
    await exerciseReview(page);
    await confirmExercise(page);
    const original = inspectOwnedSyntheticData(owner.email).exerciseRecords[0];
    await beginExercise(page);
    await activity(page, 'Find activity or movement', 'Treadmill walking', 'Treadmill walking');
    await page.getByLabel('Record date', { exact: true }).fill('2020-01-02');
    await page.getByLabel('Duration (minutes)', { exact: true }).fill('20');
    await page.getByText('Training details (optional)', { exact: true }).click();
    await page.getByLabel('Speed (km/h)', { exact: true }).fill('-1');
    await expect(page.getByRole('button', { name: 'Review exercise entry', exact: true })).toBeDisabled();
    expect(inspectOwnedSyntheticData(owner.email).exerciseRecords).toHaveLength(1);
    await page.getByLabel('Speed (km/h)', { exact: true }).fill('5');
    await page.getByLabel('Incline (%)', { exact: true }).fill('0');
    await page.getByLabel('Distance (m)', { exact: true }).fill('1000');
    await exerciseReview(page);
    await confirmExercise(page);
    const data = inspectOwnedSyntheticData(owner.email);
    expect(data.exerciseRecords).toHaveLength(2);
    expect(data.exerciseRecords[1].estimatedKj).toBe(original.estimatedKj);
    const roots = await exerciseRoots(page), withDetails = roots.results.find(r => r.input.kind === 'QUICK' && 'optionId' in r.input.period && r.input.period.equipmentDetails.speedKmh === 5)!;
    expect(withDetails.input).toMatchObject({ kind: 'QUICK', period: { durationMinutes: 20, equipmentDetails: { speedKmh: 5, inclinePercent: 0, distanceMetres: 1000 } } });
    expect(data.receipts).toHaveLength(2);
});
