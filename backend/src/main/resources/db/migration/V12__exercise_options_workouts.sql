CREATE FUNCTION validate_exercise_option_snapshot() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE opt exercise_option;
BEGIN
 IF NEW.exercise_option_id IS NULL THEN RETURN NULL; END IF;
 SELECT * INTO opt FROM exercise_option WHERE id=NEW.exercise_option_id;
 IF opt.id IS NULL OR opt.review_status<>'REVIEWED' OR opt.period_kind<>NEW.period_kind OR NEW.exercise_type_id IS DISTINCT FROM opt.reference_id OR
  (opt.mapping_kind='UNAVAILABLE' AND (NEW.estimate_status<>'NO_APPLICABLE_REFERENCE' OR NEW.estimated_kj IS NOT NULL OR NEW.met_used IS NOT NULL OR NEW.weight_kg_used IS NOT NULL OR NEW.weight_date_used IS NOT NULL OR NEW.formula_version IS NOT NULL)) OR
  EXISTS(SELECT 1 FROM jsonb_object_keys(NEW.equipment_details) k WHERE NOT(opt.allowed_details ? k)) THEN RAISE EXCEPTION 'Invalid option snapshot or unsupported details' USING ERRCODE='23514'; END IF;
 IF NOT opt.active AND (TG_OP='INSERT' OR OLD.exercise_option_id IS DISTINCT FROM NEW.exercise_option_id) THEN RAISE EXCEPTION 'New activity requires active option' USING ERRCODE='23514'; END IF;
 RETURN NULL;
END $$;
CREATE CONSTRAINT TRIGGER exercise_option_snapshot_check AFTER INSERT OR UPDATE ON exercise_record DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION validate_exercise_option_snapshot();
