-- UX-D00 / UX-BC01: UX metadata only. Official catalogue values and legacy records are unchanged.
CREATE TABLE food_search_profile (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reference_id bigint NOT NULL REFERENCES food_reference(id) ON DELETE RESTRICT,
    metadata_revision varchar(100) NOT NULL CHECK (btrim(metadata_revision)<>''),
    is_active boolean NOT NULL DEFAULT false,
    review_status varchar(16) NOT NULL CHECK (review_status IN ('DRAFT','REVIEWED','REJECTED')),
    short_name_en text NOT NULL CHECK (btrim(short_name_en)<>''),
    short_name_zh text,
    concept_key varchar(100),
    facets jsonb NOT NULL DEFAULT '{}'::jsonb CHECK (jsonb_typeof(facets)='object'),
    common_rank integer NOT NULL DEFAULT 0 CHECK (common_rank>=0),
    evidence jsonb NOT NULL CHECK (jsonb_typeof(evidence)='object' AND evidence ? 'field' AND evidence ? 'text'),
    search_vector tsvector GENERATED ALWAYS AS (to_tsvector('simple'::regconfig,short_name_en)) STORED,
    CONSTRAINT food_search_profile_revision_unique UNIQUE(reference_id,metadata_revision),
    CONSTRAINT food_search_active_reviewed CHECK (NOT is_active OR review_status='REVIEWED')
);
CREATE UNIQUE INDEX food_search_profile_one_active ON food_search_profile(reference_id) WHERE is_active AND review_status='REVIEWED';
CREATE INDEX food_search_profile_vector ON food_search_profile USING gin(search_vector);
CREATE INDEX food_search_profile_concept ON food_search_profile(concept_key,metadata_revision) WHERE is_active AND review_status='REVIEWED';
CREATE TABLE food_search_alias (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    profile_id bigint REFERENCES food_search_profile(id) ON DELETE RESTRICT,
    concept_key varchar(100),
    locale varchar(8) NOT NULL CHECK (locale IN ('en','zh')),
    normalised_text varchar(80) NOT NULL CHECK (btrim(normalised_text)<>''),
    metadata_revision varchar(100) NOT NULL CHECK (btrim(metadata_revision)<>''),
    review_status varchar(16) NOT NULL CHECK (review_status IN ('DRAFT','REVIEWED','REJECTED')),
    CONSTRAINT food_search_alias_one_target CHECK ((profile_id IS NULL) <> (concept_key IS NULL))
);
-- Multi-reference aliases are allowed; only identical target/revision duplicates are excluded.
CREATE UNIQUE INDEX food_search_alias_profile_unique ON food_search_alias(profile_id,locale,normalised_text,metadata_revision) WHERE profile_id IS NOT NULL;
CREATE UNIQUE INDEX food_search_alias_concept_unique ON food_search_alias(concept_key,locale,normalised_text,metadata_revision) WHERE concept_key IS NOT NULL;
CREATE INDEX food_search_alias_lookup ON food_search_alias(normalised_text,locale,metadata_revision) WHERE review_status='REVIEWED';
