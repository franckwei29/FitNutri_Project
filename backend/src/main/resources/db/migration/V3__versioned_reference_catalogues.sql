-- Published versions/IDs/nutrients are immutable; active selection is the only mutable reference field.
CREATE FUNCTION protect_catalogue_history() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN
    IF TG_OP='DELETE' THEN RAISE EXCEPTION 'Catalogue history must be deactivated, not deleted' USING ERRCODE='23514'; END IF;
    IF (to_jsonb(NEW)-'is_active') IS DISTINCT FROM (to_jsonb(OLD)-'is_active') THEN
        RAISE EXCEPTION 'Catalogue content is immutable; import a new revision' USING ERRCODE='23514';
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER food_dataset_history BEFORE UPDATE OR DELETE ON food_dataset FOR EACH ROW EXECUTE FUNCTION protect_catalogue_history();
CREATE TRIGGER activity_dataset_history BEFORE UPDATE OR DELETE ON activity_dataset FOR EACH ROW EXECUTE FUNCTION protect_catalogue_history();
CREATE TRIGGER food_reference_history BEFORE UPDATE OR DELETE ON food_reference FOR EACH ROW EXECUTE FUNCTION protect_catalogue_history();
CREATE TRIGGER exercise_type_history BEFORE UPDATE OR DELETE ON exercise_type FOR EACH ROW EXECUTE FUNCTION protect_catalogue_history();
