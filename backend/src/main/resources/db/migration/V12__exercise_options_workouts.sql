-- UX-D03: product choices are separate from official energy references; movements never carry time/energy.
CREATE FUNCTION ux_string_list(value jsonb,allowed text[] DEFAULT NULL) RETURNS boolean LANGUAGE plpgsql IMMUTABLE AS $$
DECLARE x jsonb;
BEGIN
 IF jsonb_typeof(value) IS DISTINCT FROM 'array' THEN RETURN false; END IF;
 IF jsonb_array_length(value)>100 THEN RETURN false; END IF;
 FOR x IN SELECT * FROM jsonb_array_elements(value) LOOP
  IF jsonb_typeof(x)<>'string' OR length(btrim(x#>>'{}')) NOT BETWEEN 1 AND 80 OR (allowed IS NOT NULL AND NOT((x#>>'{}')=ANY(allowed))) THEN RETURN false; END IF;
 END LOOP;
 RETURN (SELECT count(DISTINCT item.element) FROM jsonb_array_elements(value) AS item(element))=jsonb_array_length(value);
END $$;
CREATE TABLE exercise_option (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 option_key varchar(100) NOT NULL CHECK(btrim(option_key)<>''),revision varchar(100) NOT NULL CHECK(btrim(revision)<>''),
 active boolean NOT NULL DEFAULT false,
 category varchar(24) NOT NULL CHECK(category IN ('CARDIO','STRENGTH','SPORTS','OUTDOOR_OTHER')),
 period_kind varchar(16) NOT NULL CHECK(period_kind IN ('ACTIVITY','STRENGTH')),
 display_name varchar(100) NOT NULL CHECK(btrim(display_name)<>''),
 aliases jsonb NOT NULL DEFAULT '[]' CHECK(ux_string_list(aliases)),
 allowed_details jsonb NOT NULL DEFAULT '[]' CHECK(ux_string_list(allowed_details,ARRAY['speedKmh','inclinePercent','distanceMetres','machineLevel'])),
 reference_id bigint REFERENCES exercise_type(id) ON DELETE RESTRICT,
 mapping_kind varchar(32) NOT NULL CHECK(mapping_kind IN ('SPECIFIC_REFERENCE','GENERAL_ACTIVITY_ESTIMATE','UNAVAILABLE')),
 mapping_evidence jsonb NOT NULL CHECK(jsonb_typeof(mapping_evidence)='object' AND jsonb_typeof(mapping_evidence->'reason')='string' AND btrim(mapping_evidence->>'reason')<>''),
 review_status varchar(16) NOT NULL CHECK(review_status IN ('DRAFT','REVIEWED','REJECTED')),
 CONSTRAINT exercise_option_revision_unique UNIQUE(option_key,revision),
 CONSTRAINT exercise_option_mapping_shape CHECK((mapping_kind='UNAVAILABLE' AND reference_id IS NULL) OR (mapping_kind<>'UNAVAILABLE' AND reference_id IS NOT NULL)),
 CONSTRAINT exercise_option_active_reviewed CHECK(NOT active OR review_status='REVIEWED'),
 CONSTRAINT exercise_option_strength_kind CHECK((category='STRENGTH')=(period_kind='STRENGTH'))
);
CREATE UNIQUE INDEX exercise_option_one_active ON exercise_option(option_key) WHERE active;
