#!/usr/bin/env python3
"""Generate TypeScript and Zod contract boundaries from reviewed OpenAPI.
Run without arguments to verify drift; --write updates the two generated files.
"""
import json
from pathlib import Path
import sys
ROOT=Path(__file__).resolve().parents[1]
schemas=json.loads((ROOT/'docs/api/openapi-mvp.yaml').read_text())['components']['schemas']
def q(v):return json.dumps(v,ensure_ascii=False)
def ts(s):
    if '$ref' in s:return s['$ref'].rsplit('/',1)[1]
    if 'const' in s:return q(s['const'])
    if 'enum' in s:return ' | '.join(q(v) for v in s['enum'])
    if 'anyOf' in s:return ' | '.join(ts(v) for v in s['anyOf'])
    t=s.get('type')
    if isinstance(t,list):return ' | '.join(ts({'type':v}) for v in t)
    if t=='array':return 'Array<'+ts(s['items'])+'>'
    if t=='object':
        if 'properties' not in s:return 'Record<string, '+ts(s['additionalProperties'])+'>'
        return '{\n'+''.join('  '+k+('' if k in s.get('required',[]) else '?')+': '+ts(v)+';\n' for k,v in s['properties'].items())+'}'
    return {'string':'string','integer':'number','number':'number','boolean':'boolean','null':'null'}[t]
def zod(s, strict=False):
    if '$ref' in s:return 'z.lazy(() => '+s['$ref'].rsplit('/',1)[1]+'Schema)'
    if 'const' in s:return 'z.literal('+q(s['const'])+')'
    if 'enum' in s:return 'z.enum('+q(s['enum'])+')'
    if 'anyOf' in s:return 'z.union(['+', '.join(zod(v, strict) for v in s['anyOf'])+'])'
    t=s.get('type')
    if isinstance(t,list):return 'z.union(['+', '.join(zod({'type':v}, strict) for v in t)+'])'
    if t=='object':
        if 'properties' not in s:return 'z.record(z.string(), '+zod(s['additionalProperties'], strict)+')'
        return 'z.object({\n'+''.join('  '+k+': '+zod(v, strict)+('' if k in s.get('required',[]) else '.optional()')+',\n' for k,v in s['properties'].items())+'})'+('.strict()' if strict else '')
    if t=='array':
        result='z.array('+zod(s['items'], strict)+')'
        for key,method in [('minItems','min'),('maxItems','max')]:
            if key in s:result+='.'+method+'('+str(s[key])+')'
        return result
    result={'string':'z.string()','integer':'z.number().int().nonnegative()','number':'z.number().finite()','boolean':'z.boolean()','null':'z.null()'}[t]
    if t=='string':
        fmt=s.get('format')
        if fmt=='date':result+='.refine(isValidLocalDate, "Invalid calendar date")'
        elif fmt=='date-time':result='z.iso.datetime({ offset: true })'
        elif fmt=='uuid':result='z.uuid()'
        elif fmt=='email':result='z.email()'
        elif fmt=='uri':result='z.url()'
        for key,method in [('minLength','min'),('maxLength','max')]:
            if key in s:result+='.'+method+'('+str(s[key])+')'
        if 'pattern' in s:result+='.regex(new RegExp('+q(s['pattern'])+'))'
    if t in ['number','integer']:
        for key,method in [('minimum','min'),('maximum','max'),('exclusiveMinimum','gt'),('multipleOf','multipleOf')]:
            if key in s:result+='.'+method+'('+str(s[key])+')'
    return result
header='// Generated by scripts/generate_api_types.py from docs/api/openapi-mvp.yaml.\n// Do not edit by hand. Target contract only; implementations are tracked separately.\n'
outputs={ROOT/'frontend/src/api/contracts.ts':header+'\n'+''.join('export type '+name+' = '+ts(s)+';\n\n' for name,s in schemas.items()),
         ROOT/'frontend/src/api/schemas.ts':header+'import { z } from "zod";\nimport { isValidLocalDate } from "../domain/dates";\n\n'+''.join('export const '+name+'Schema = '+zod(s, name.endswith('Request') or name.endswith('V2'))+';\n\n' for name,s in schemas.items())}
for path,content in outputs.items():
    if '--write' in sys.argv:path.write_text(content)
    elif not path.exists() or path.read_text()!=content:raise SystemExit('Contract drift: '+str(path))
print(('Generated' if '--write' in sys.argv else 'PASS: no drift in')+f' {len(schemas)} TypeScript types and Zod schemas.')
