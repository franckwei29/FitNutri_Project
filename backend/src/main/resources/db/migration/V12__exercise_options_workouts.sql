CREATE FUNCTION equipment_details_valid(value jsonb) RETURNS boolean LANGUAGE plpgsql IMMUTABLE AS $$
DECLARE k text; v jsonb; n numeric;
BEGIN
 IF jsonb_typeof(value) IS DISTINCT FROM 'object' OR value-ARRAY['speedKmh','inclinePercent','distanceMetres','machineLevel']<>'{}' THEN RETURN false; END IF;
 FOR k,v IN SELECT * FROM jsonb_each(value) LOOP
  IF v='null'::jsonb THEN CONTINUE; END IF;
  IF jsonb_typeof(v)<>'number' THEN RETURN false; END IF;n=(v#>>'{}')::numeric;
  IF n<>round(n,2) THEN RETURN false; END IF;
  IF (k='speedKmh' AND (n<=0 OR n>100)) OR (k='inclinePercent' AND (n< -20 OR n>40)) OR (k='distanceMetres' AND (n<=0 OR n>1000000)) OR (k='machineLevel' AND (n<0 OR n>100 OR n<>trunc(n))) THEN RETURN false; END IF;
 END LOOP;RETURN true;
EXCEPTION WHEN OTHERS THEN RETURN false;
END $$;
