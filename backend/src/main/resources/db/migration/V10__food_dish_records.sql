-- UX-D01: occurrence roots and precise consumed leaves; no old records are grouped or recalculated.
CREATE FUNCTION dish_portion_is_valid(mode text,kind text,n bigint,d bigint,value jsonb)
RETURNS boolean LANGUAGE plpgsql IMMUTABLE AS $$
DECLARE a numeric; b numeric;
BEGIN
 IF n IS NULL OR d IS NULL OR n<=0 OR d<=0 OR n>d OR gcd(n,d)<>1 OR jsonb_typeof(value)<>'object' THEN RETURN false; END IF;
 IF mode='PERSONAL' THEN RETURN kind='PERSONAL' AND n=1 AND d=1 AND value='{}'::jsonb; END IF;
 IF mode<>'FULL_RECIPE' THEN RETURN false; END IF;
 IF kind='FRACTION' THEN
  IF value-ARRAY['numerator','denominator']<>'{}' OR NOT(value ?& ARRAY['numerator','denominator']) OR jsonb_typeof(value->'numerator')<>'number' OR jsonb_typeof(value->'denominator')<>'number' THEN RETURN false; END IF;
  a=(value->>'numerator')::numeric; b=(value->>'denominator')::numeric;
  RETURN a BETWEEN 1 AND 1000000 AND b BETWEEN 1 AND 1000000 AND a=trunc(a) AND b=trunc(b) AND a<=b AND a*d=b*n;
 ELSIF kind='PERCENT' THEN
  IF value-'percent'<>'{}' OR jsonb_typeof(value->'percent') IS DISTINCT FROM 'number' THEN RETURN false; END IF;
  a=(value->>'percent')::numeric;
  RETURN a>0 AND a<=100 AND a=round(a,3) AND a*d=100*n;
 ELSIF kind='SERVINGS' THEN
  IF value-ARRAY['total','eaten']<>'{}' OR NOT(value ?& ARRAY['total','eaten']) OR jsonb_typeof(value->'total')<>'number' OR jsonb_typeof(value->'eaten')<>'number' THEN RETURN false; END IF;
  a=(value->>'total')::numeric;b=(value->>'eaten')::numeric;
  RETURN a BETWEEN 1 AND 1000 AND a=trunc(a) AND b>0 AND b<=a AND b=round(b,3) AND b*d=a*n;
 END IF;
 RETURN false;
EXCEPTION WHEN OTHERS THEN RETURN false;
END $$;
CREATE TABLE food_dish_record (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id bigint NOT NULL REFERENCES app_user(id) ON DELETE RESTRICT,
 client_entry_id uuid NOT NULL,
 name varchar(100) NOT NULL CHECK(length(btrim(name)) BETWEEN 1 AND 100),
 recorded_date date NOT NULL,
 meal_type varchar(16) NOT NULL CHECK(meal_type IN ('BREAKFAST','LUNCH','DINNER','SNACK')),
 input_mode varchar(16) NOT NULL CHECK(input_mode IN ('PERSONAL','FULL_RECIPE')),
 portion_input_kind varchar(16) NOT NULL CHECK(portion_input_kind IN ('PERSONAL','FRACTION','PERCENT','SERVINGS')),
 portion_numerator bigint NOT NULL,
 portion_denominator bigint NOT NULL,
 portion_input_json jsonb NOT NULL,
 source varchar(16) NOT NULL CHECK(source IN ('MANUAL','VOICE','IMAGE')),
 origin_dish_id bigint,
 created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
 version bigint NOT NULL DEFAULT 0 CHECK(version>=0),
 deleted_at timestamptz,
 CONSTRAINT food_dish_client_unique UNIQUE(user_id,client_entry_id),
 CONSTRAINT food_dish_owned_identity UNIQUE(id,user_id),
 CONSTRAINT food_dish_portion_valid CHECK(dish_portion_is_valid(input_mode,portion_input_kind,portion_numerator,portion_denominator,portion_input_json)),
 CONSTRAINT food_dish_origin_owner FOREIGN KEY(origin_dish_id,user_id) REFERENCES food_dish_record(id,user_id) DEFERRABLE INITIALLY DEFERRED,
 CONSTRAINT food_dish_origin_not_self CHECK(origin_dish_id IS NULL OR origin_dish_id<>id)
);
