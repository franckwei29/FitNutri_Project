CREATE FUNCTION protect_ux_catalogue_history() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF TG_OP='DELETE' THEN RAISE EXCEPTION 'Catalogue identities must be retained' USING ERRCODE='23514'; END IF;
 IF OLD.review_status='REVIEWED' AND (to_jsonb(NEW)-'active') IS DISTINCT FROM (to_jsonb(OLD)-'active') THEN RAISE EXCEPTION 'Published UX mappings require a new revision' USING ERRCODE='23514'; END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER exercise_option_history BEFORE UPDATE OR DELETE ON exercise_option FOR EACH ROW EXECUTE FUNCTION protect_ux_catalogue_history();
CREATE TRIGGER movement_catalogue_history BEFORE UPDATE OR DELETE ON movement_catalogue FOR EACH ROW EXECUTE FUNCTION protect_ux_catalogue_history();
