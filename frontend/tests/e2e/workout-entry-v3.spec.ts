import {ExerciseRootV2Schema} from '../../src/api/schemas'
import { test, expect } from '@playwright/test';
import { newOwner, history } from './v3-journeys';
import { beginExercise, activity, exerciseReview, confirmExercise, exerciseRoots } from './v3-exercise-journeys';
import { inspectGroups } from './owned-v3-verification';
import { inspectOwnedSyntheticData } from './owned-db-verification.mjs';
test('TUX Gym: one50minute strength period plus20minute unavailable cardio,optional movement details,whole-root correction/reuse/delete', async ({ page }) => {
    const owner = await newOwner(page, 'v3-gym');
    await beginExercise(page, '2020-01-02', true);
    await page.getByLabel('Workout title', { exact: true }).fill('Synthetic full gym session');
    const strength = page.getByRole('group', { name: 'Strength period 1', exact: true });
    await activity(strength, 'Strength activity', 'Strength training', 'Strength training');
    await strength.getByLabel('Duration (minutes)', { exact: true }).fill('50');
    await strength.getByRole('combobox', { name: 'Find movement', exact: true }).fill('Bench press');
    await page.getByRole('option', { name: 'Bench press', exact: true }).click();
    await strength.getByLabel('Sets 1', { exact: true }).fill('0');
    await expect(page.getByRole('button', { name: 'Review workout', exact: true })).toBeDisabled();
    await strength.getByLabel('Sets 1', { exact: true }).fill('3');
    await strength.getByLabel('Reps per set 1', { exact: true }).fill('8');
    await strength.getByLabel('Load including bar (kg) 1', { exact: true }).fill('20');
    await page.getByRole('button', { name: 'Add cardio period', exact: true }).click();
    const cardio = page.getByRole('group', { name: 'Cardio period 2', exact: true });
    await activity(cardio, 'Activity for period 2', 'Treadmill running', 'Treadmill running');
    await cardio.getByLabel('Duration (minutes)', { exact: true }).fill('20');
    await expect(page.getByText('Total recorded time: 70 minutes', { exact: true })).toBeVisible();
    await exerciseReview(page, true);
    expect(inspectOwnedSyntheticData(owner.email).exerciseRecords).toHaveLength(0);
    const proof = await confirmExercise(page);
    expect(proof.roots.map(r => r.kind)).toEqual(['WORKOUT']);
    expect(proof.leaves).toHaveLength(2);
    await expect(page.getByRole('heading', {name:'A little progress, every day.',exact:true})).toBeVisible();
    await expect(page.getByLabel('Latest saved records')).toContainText('2020-01-02');
    const roots = await exerciseRoots(page), root = roots.results[0];
    expect(ExerciseRootV2Schema.safeParse(root)).toMatchObject({success:true});
    expect(root.periodCount).toBe(2);
    expect(root.preview).toMatchObject({ totalMinutes: 70, partial: true });
    expect(root.preview.knownEnergyKj).toBeGreaterThan(0);
    expect(root.preview.periods[1]).toMatchObject({ status: 'NO_APPLICABLE_REFERENCE', estimatedKj: null });
    expect(root.periodDetails[0].movements[0]).toMatchObject({ name: 'Bench press', setCount: 3, repetitions: 8, loadKg: 20, loadBasis: 'TOTAL_BARBELL' });
    const saved = inspectOwnedSyntheticData(owner.email);
    expect(saved.exerciseRecords).toHaveLength(2);
    const sql = inspectGroups(owner.email);
    expect(sql.workouts).toHaveLength(1);
    expect(sql.periods).toHaveLength(2);
    expect(sql.movements).toEqual([expect.objectContaining({ name: 'Bench press', sets: 3, reps: 8, loadKg: 20, basis: 'TOTAL_BARBELL' })]);
    expect(sql.movementAuthorityColumns).toBe(0);
    expect(sql.ledger).toMatchObject({ exerciseMinutes: 70, exerciseRoots: 1, exercisePeriods: 2 });
    await history(page, '2020-01-02', 'exercise');
    await expect(page.locator('article.saved-entry-root')).toHaveCount(1);
    let card = page.locator(`[data-record-id="workout:${root.id}"]`);
    await expect(card).toContainText('70 minutes · 2 periods');
    await card.getByRole('button', { name: /More actions for/ }).click(); await page.getByRole('menuitem', { name: 'Edit', exact: true }).click();
    await page.getByText('Adjust exercise details',{exact:true}).click();
    await page.getByLabel('Workout title', { exact: true }).fill('Corrected same occurrence');
    await page.getByRole('button', { name: 'Confirm changes', exact: true }).click();
    await expect(page).toHaveURL(/\/history\?/);
    const changed = (await exerciseRoots(page)).results[0];
    expect(changed.id).toBe(root.id);
    expect(changed.version).toBe(1);
    expect(changed.preview).toMatchObject({ ...root.preview, inputSignature: expect.any(String) });
    expect(changed.preview.inputSignature).not.toBe(root.preview.inputSignature);
    expect(inspectOwnedSyntheticData(owner.email).exerciseRecords).toEqual(saved.exerciseRecords);
    card = page.locator(`[data-record-id="workout:${root.id}"]`);
    await card.getByRole('button', { name: /More actions for/ }).click(); await page.getByRole('menuitem', { name: 'Log again', exact: true }).click();
    await expect(page.getByRole('heading', { name: 'Add exercise', exact: true })).toBeVisible();
    for (const duration of await page.getByLabel('Duration (minutes)', { exact: true }).all())
        await expect(duration).toHaveValue('');
    await expect(page.getByLabel('Sets 1', { exact: true })).toHaveValue('');
    await expect(page.getByLabel('Reps per set 1', { exact: true })).toHaveValue('');
    await expect(page.getByLabel('Load including bar (kg) 1', { exact: true })).toHaveValue('');
    await page.getByRole('button', { name: 'Use last duration (50 min)', exact: true }).click();
    await page.getByRole('button', { name: 'Use last duration (20 min)', exact: true }).click();
    await page.getByRole('button', { name: 'Use last details', exact: true }).click();
    await expect(page.getByLabel('Sets 1', { exact: true })).toHaveValue('3');
    expect(inspectOwnedSyntheticData(owner.email).exerciseRecords).toEqual(saved.exerciseRecords);
    await page.getByRole('link', { name: 'History', exact: true }).click();
    await page.getByRole('button', { name: 'Discard and leave', exact: true }).click();
    await history(page, '2020-01-02', 'exercise');
    card = page.locator(`[data-record-id="workout:${root.id}"]`);
    await card.getByRole('button', { name: /More actions for/ }).click(); await page.getByRole('menuitem', { name: 'Delete', exact: true }).click();
    await page.getByRole('button', { name: 'Confirm deletion', exact: true }).click();
    await expect(page.locator('article.saved-entry-root')).toHaveCount(0);
    const deleted = inspectOwnedSyntheticData(owner.email);
    expect(deleted.exerciseRecords).toHaveLength(2);
    expect(deleted.exerciseRecords.every(r => r.deleted)).toBe(true);
    expect(deleted.receipts).toEqual(saved.receipts);
    await page.screenshot({ path: 'test-results/ux-v3/workout-deleted-root.png', fullPage: true });
});
